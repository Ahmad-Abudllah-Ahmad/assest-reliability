export function initializeSolarFleetReliability(): {
  assets: SolarAsset[];
  alerts: any[];
  recommendations: any[];
} {
  const recalculatedAssets = RAW_SOLAR_FLEET.map((asset) =>
    recalculateSolarAsset(asset, INITIAL_SOLAR_RULES, INITIAL_SOLAR_PLANT_CONTEXT)
  );

  let allAlerts: any[] = [];
  recalculatedAssets.forEach((asset) => {
    if (asset.triggeredRules.length > 0) {
      const generated = generateSolarAlertsFromRules(asset, asset.triggeredRules);
      allAlerts = [...allAlerts, ...generated];
    }
  });

  const allRecommendations = generateSolarRecommendationsFromAlerts(allAlerts);

  return {
    assets: recalculatedAssets,
    alerts: allAlerts,
    recommendations: allRecommendations
  };
}

